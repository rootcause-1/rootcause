"""Scorecard: reads every (:ChaosRun) of an eval graph (list_chaos_runs) and writes docs/SCORECARD.md.

All numbers are computed from recorded runs; nothing is typed by hand.
"""

from __future__ import annotations

import statistics
from collections import defaultdict
from pathlib import Path
from typing import Any

from rootcause.graph.client import GraphDB
from rootcause.util import loads

METHODS = ("rootcause", "graph_off", "llm_no_graph", "loudest_alert", "first_alert", "highest_error")


def hit(ranked: list[str] | None, truth: str, k: int) -> bool | None:
    if ranked is None:
        return None
    return any(t.strip() in ranked[:k] for t in truth.split(" | "))


def render(runs: list[dict[str, Any]], batch: str) -> str:
    lines = [f"# Scorecard — batch `{batch}`", "",
             f"{len(runs)} blind chaos runs. Generated by `make chaos`; do not edit by hand.", "",
             "| method | top-1 | top-3 | median time to verdict | runs scored |", "|---|---|---|---|---|"]
    per_method: dict[str, dict[str, list[Any]]] = defaultdict(lambda: {"t1": [], "t3": []})
    per_class: dict[str, list[bool]] = defaultdict(list)
    misses = []
    for r in runs:
        results = loads(r.get("results"), {}) or {}
        for m in METHODS:
            ranked = results.get(m)
            t1, t3 = hit(ranked, r["truth"], 1), hit(ranked, r["truth"], 3)
            if t1 is not None:
                per_method[m]["t1"].append(t1)
                per_method[m]["t3"].append(t3)
        per_class[r.get("class") or "?"].append(bool(r.get("top1")))
        if not r.get("top1"):
            misses.append(r)
    ttd = [int(r["ttd_ms"]) for r in runs if r.get("ttd_ms")]
    for m in METHODS:
        d = per_method.get(m)
        if not d or not d["t1"]:
            lines.append(f"| {m} | - | - | - | 0 |")
            continue
        med = f"{statistics.median(ttd) / 1000:.0f} s" if (m == "rootcause" and ttd) else "-"
        lines.append(f"| {m} | {sum(d['t1']) / len(d['t1']):.0%} | {sum(d['t3']) / len(d['t3']):.0%} | {med} | "
                     f"{len(d['t1'])} |")
    lines += ["", "## RootCause top-1 by fault class", "", "| class | top-1 | runs |", "|---|---|---|"]
    for cls, hits in sorted(per_class.items()):
        lines.append(f"| {cls} | {sum(hits) / len(hits):.0%} | {len(hits)} |")
    lines += ["", "## Misses", ""]
    lines += [f"- `{r['flag']}` (truth `{r['truth']}`): verdict `{r.get('verdict')}` — {r.get('miss_reason') or '?'}"
              for r in misses] or ["- none"]
    return "\n".join(lines) + "\n"


async def write(eval_db: GraphDB, batch: str, docs_dir: str) -> str:
    runs = [r["run"] for r in await eval_db.run("list_chaos_runs")]
    md = render(runs, batch)
    Path(docs_dir).mkdir(parents=True, exist_ok=True)
    (Path(docs_dir) / "SCORECARD.md").write_text(md, encoding="utf-8")
    return md
